import { buildIdentification, classifyDeviceType, modelFromSnapshot } from '../lib/model';
import { REGISTER_SETS } from '../lib/registers';
let f = 0; const ok = (c: boolean, s: string) => { if (!c) f++; console.log(c ? 'ok  ' : 'FAIL', s); };
const m = (value: string) => ({ value, scale: 0, label: '', group: 'info' });
(async () => {
  const snap: any = { devicetype: m('0005'), generation: m('4'), protocolversion: m('0104'), ratedpower: m('120000'), localization: m('0') };
  const id = modelFromSnapshot(snap)!;
  ok(id.modelString === 'SUN-12K-SG04LP3-EU', 'SG04LP3, 12 kW, EU: ' + id.modelString);
  ok(id.protocolVersion === '1.04' && id.ratedPowerW === 12000 && id.family === 'three-phase-lv-hybrid', 'protocol 1.04, 12000 W, family');
  ok(id.notes.length === 2, 'notes: power class and generation > 2');
  ok(modelFromSnapshot({ ...snap, devicetype: m('0006') })!.modelString === 'SUN-12K-SG04HP3-EU', 'high voltage = HP3');
  ok(modelFromSnapshot({ ...snap, devicetype: m('0300') })!.modelString === 'SUN-12K-SG04LP1-EU', 'single phase = LP1');
  ok(modelFromSnapshot({ ...snap, localization: m('1') })!.modelString === 'SUN-12K-SG04LP3-US', 'US market');
  ok(modelFromSnapshot({ ...snap, ratedpower: m('0') })!.modelString === 'SUN-SG04LP3-EU', 'no rated power: no power class');
  ok(modelFromSnapshot({ ...snap, ratedpower: m('85000') })!.modelString === 'SUN-8.5K-SG04LP3-EU', 'one decimal: 8.5K');
  const { localization, ...noMarket } = snap;
  ok(modelFromSnapshot(noMarket)!.modelString === 'SUN-12K-SG04LP3', 'market register missing: no market suffix');
  ok(modelFromSnapshot({ ...snap, devicetype: m('1234') })!.modelString.startsWith('Deye inverter (device type 0x1234'), 'unknown device type: generic text');
  const { generation, ...noGen } = snap;
  ok(modelFromSnapshot(noGen) === null, 'generation missing: null');
  ok(classifyDeviceType(0x0500) === 'three-phase-lv-hybrid' && classifyDeviceType(0x0601) === 'three-phase-hv-hybrid', 'later device type forms');
  ok(buildIdentification({ deviceType: 5, generation: 4, protocolVersionWord: null, ratedPowerRaw: null, market: null }).protocolVersion === null, 'no protocol word');
  const sets = REGISTER_SETS as any[];
  const want: Record<string, number> = { devicetype: 0, protocolversion: 2, localization: 26, generation: 28 };
  ok(sets.every((s) => Object.entries(want).every(([k, a]) => s.registers[k]?.address === a)), 'identification registers 0, 2, 26, 28 are read');
  process.exit(f ? 1 : 0);
})();
